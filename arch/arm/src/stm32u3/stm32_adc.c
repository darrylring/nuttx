/****************************************************************************
 * Name: stm32_adc_initialize
 ****************************************************************************/

struct adc_dev_s *stm32_adc_initialize(int intf, const uint8_t *chanlist,
                                       int nchannels)
{
  struct adc_dev_s *dev;
  struct stm32_dev_s *priv;
  int i;

  ainfo("intf: %d nchannels: %d\n", intf, nchannels);

  switch (intf)
    {
#ifdef CONFIG_STM32_ADC1
      case 1:
        dev = &g_adcdev1;
        break;
#endif
#ifdef CONFIG_STM32_ADC2
      case 2:
        dev = &g_adcdev2;
        break;
#endif
      default:
        aerr("ERROR: No such ADC interface: %d\n", intf);
        return NULL;
    }

  if (nchannels < 1 || nchannels > CONFIG_STM32_ADC_MAX_SAMPLES ||
      nchannels > 16)
    {
      aerr("ERROR: Invalid number of channels: %d\n", nchannels);
      return NULL;
    }

  for (i = 0; i < nchannels; i++)
    {
      /* VCORE (18) has no documented enable bit in RM0487 Rev 3 */

      if (chanlist[i] >= ADC_CH_VCORE)
        {
          aerr("ERROR: Invalid channel: %d\n", chanlist[i]);
          return NULL;
        }
    }

  priv = (struct stm32_dev_s *)dev->ad_priv;
  priv->cb        = NULL;
  priv->cchannels = nchannels;
  memcpy(priv->chanlist, chanlist, nchannels);

  return dev;
}

